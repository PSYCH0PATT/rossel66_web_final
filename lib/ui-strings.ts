/**
 * Счётчик «показано N из M»: «Показано 1–4 из 4 релизов».
 * Слово в правильной форме берётся из `plural`, поэтому «1 релиз», но «4 релиза».
 */
export function paginationSummary(
  from: number,
  to: number,
  total: number,
  forms: readonly [string, string, string] = ["релиз", "релиза", "релизов"]
): string {
  return `Показано ${from}–${to} из ${total} ${plural(total, forms)}`
}

/** Счётчик записей одной строкой: «Всего 12 отчётов». */
export function totalSummary(
  total: number,
  forms: readonly [string, string, string]
): string {
  return `Всего ${pluralize(total, forms)}`
}

