/**
 * Классификация прослушивания по полю `length` из rossel_flash на платное/бесплатное.
 *
 * Реальные категории в CSV (колонка length):
 *   - "Полный стрим"            — платный (полное прослушивание)
 *   - "Платный стрим (30+ сек)" — платный (монетизируемый, 30+ сек)
 *   - "6-29 сек"                — бесплатный
 *   - "0-5 сек"                 — бесплатный
 *
 * Решение: две категории. Платные = {Полный, 30+}, бесплатные = всё 0–29 сек.
 */
const PAID_STREAM_LENGTHS = new Set<string>([
  'полный стрим',
  'платный стрим (30+ сек)',
  'full', // англ. вариант «Полный стрим» в некоторых выгрузках
])

/** true, если длительность стрима относится к платным (монетизируемым). */
export function isPaidStreamLength(length: string | null | undefined): boolean {
  if (!length) return false
  return PAID_STREAM_LENGTHS.has(length.trim().toLowerCase())
}
