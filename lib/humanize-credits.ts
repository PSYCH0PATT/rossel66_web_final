/**
 * Человекочитаемая подпись из сырой склейки площадки (F-91).
 *
 * В `track_data` плейлистов и в метаданных событий исполнители с названием
 * приезжают одной строкой вида «rompy;Лоло - беги»: имена склеены точкой с
 * запятой без пробела, между исполнителями и названием — дефис. В ленте
 * активности поверх этого лежал CSS-капс, и артист видел
 * «ROMPY;ЛОЛО - БЕГИ» — внутренний формат импорта вместо своих имён.
 *
 * Здесь правится только пунктуация и пробелы. Регистр приходит из данных и
 * не додумывается: «беги» останется «беги», пока так записано у площадки.
 */
export function humanizeCredits(raw: string | null | undefined): string {
  if (raw == null) return ""
  return String(raw)
    .split(";")
    .map((part) => part.trim())
    .filter(Boolean)
    .join(", ")
    // Дефис-разделитель между блоками — тире; дефис внутри слова не трогаем.
    .replace(/\s+[-–]\s+/g, " — ")
    .replace(/\s{2,}/g, " ")
    .trim()
}
